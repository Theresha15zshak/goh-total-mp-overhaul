"""Build-time only: writes dll/proxy_iphlpapi.c, which makes goh_replay.dll a stand-in for
IPHLPAPI.DLL. The game loads it from its own folder; every export jumps to the real
System32 iphlpapi.dll, so the game and any system DLL that imports it keep working."""
import os, struct, sys

SRC = os.path.join(os.environ['SystemRoot'], 'System32', 'iphlpapi.dll')
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'dll', 'proxy_iphlpapi.c')


def exports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    secs = [struct.unpack_from('<8sIIII', d, pe + 24 + optsz + 40 * i) for i in range(nsec)]

    def off(r):
        for _, vs, va, rs, ra in secs:
            if va <= r < va + max(vs, rs):
                return r - va + ra

    def cs(r):
        o = off(r)
        return d[o:d.index(b'\0', o)].decode()

    er = struct.unpack_from('<I', d, pe + 24 + 112)[0]
    o = off(er)
    base, nf, nn, af, anp, ano = struct.unpack_from('<IIIIII', d, o + 16)
    named = {}
    for i in range(nn):
        name = cs(struct.unpack_from('<I', d, off(anp) + 4 * i)[0])
        named[struct.unpack_from('<H', d, off(ano) + 2 * i)[0]] = name
    out = []
    for i in range(nf):
        if struct.unpack_from('<I', d, off(af) + 4 * i)[0]:
            out.append((base + i, named.get(i)))
    return out


def main():
    ex = exports(SRC)
    lines = ['// Generated by tools/gen_proxy.py from %s (%d exports). Do not edit.' % (SRC, len(ex)),
             '#include <windows.h>', '',
             '#define PROXY_COUNT %d' % len(ex),
             'void *proxy_real[PROXY_COUNT];', '']
    lines.append('static const char *const proxy_names[PROXY_COUNT] = {')
    for ordinal, name in ex:
        lines.append('    %s,' % ('"%s"' % name if name else '(const char *)(ULONG_PTR)%d' % ordinal))
    lines += ['};', '']
    asm = ['.text']
    drectve = []
    for i, (ordinal, name) in enumerate(ex):
        asm.append('.globl proxy_%d\nproxy_%d: jmp *proxy_real+%d(%%rip)' % (i, i, 8 * i))
        drectve.append(' -export:%s=proxy_%d,@%d%s' % (name, i, ordinal, '' if name else ',NONAME') if name
                       else ' -export:proxy_ord%d=proxy_%d,@%d,NONAME' % (ordinal, i, ordinal))
    lines.append('__asm__(')
    lines += ['    "%s\\n"' % a.replace('\n', '\\n') for a in asm]
    lines.append('    ".section .drectve\\n"')
    lines += ['    ".ascii \\"%s\\"\\n"' % x for x in drectve]
    lines += ['    ".text\\n");', '']
    lines += ['// Loads the real System32 DLL and fills the jump table. Returns FALSE if that fails.',
              'BOOL proxy_init(void) {',
              '    wchar_t path[MAX_PATH];',
              '    UINT n = GetSystemDirectoryW(path, MAX_PATH);',
              '    lstrcpyW(path + n, L"\\\\iphlpapi.dll");',
              '    HMODULE real = LoadLibraryW(path);',
              '    if (!real) return FALSE;',
              '    for (int i = 0; i < PROXY_COUNT; i++) proxy_real[i] = (void *)GetProcAddress(real, proxy_names[i]);',
              '    return TRUE;',
              '}', '']
    open(OUT, 'w', newline='\n').write('\n'.join(lines))
    print('wrote', OUT, len(ex), 'exports', sum(1 for _, n in ex if not n), 'by ordinal only')


if __name__ == '__main__':
    main()
